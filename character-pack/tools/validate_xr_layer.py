def r_pv_time(c, out):
    prov = c.prov
    gens = [parse_ts(j["generated_at"]) for j in prov["generation"]["jobs"]]
    scr = parse_ts(prov["similarity_screening"]["screened_at"])
    rev = parse_ts(prov["human_review"]["reviewed_at"])
    cap = parse_ts(prov["terms_evidence"]["captured_at"])
    for name, t, ptr in [("screened_at", scr, "/provenance/similarity_screening/screened_at"),
                         ("reviewed_at", rev, "/provenance/human_review/reviewed_at"),
                         ("captured_at", cap, "/provenance/terms_evidence/captured_at")]:
        if t > c.now_end:
            out.add("PV009", ptr, "%s is in the future" % name, "future:" + name)
    for i, g in enumerate(gens):
        if g > c.now_end:
            out.add("PV009", P("provenance", "generation", "jobs", i, "generated_at"), "generated_at is in the future", "future:gen%d" % i)
    if gens and scr < max(gens):
        out.add("PV009", "/provenance/similarity_screening/screened_at", "screening precedes the last generation", "order:screen")
    if rev < scr:
        out.add("PV009", "/provenance/human_review/reviewed_at", "human review precedes similarity screening", "order:review")


