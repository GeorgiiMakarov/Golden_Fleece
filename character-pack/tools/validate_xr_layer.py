REQUIRED_LIMITS = (
    "tolerance_cm", "prediction_residual_factor", "min_lever_arm_m", "headroom_warn_ratio",
    "max_hold_ms", "warn_hold_ms", "max_flash_hz", "max_estop_response_ms", "coverage_warn_pct",
    "caption_min_angle_deg", "max_retention_days", "allowed_fps", "max_clip_ms", "min_loop_ms",
    "max_frame_pixels", "max_xr_media_bytes", "max_glb_triangles", "max_texture_px",
    "terms_evidence_window_days", "max_waiver_days", "min_waiver_reason_chars",
)


class Policy(object):
    def __init__(self, data):
        if not isinstance(data, dict):
            raise InfraError("policy root must be an object")
        self.version = data.get("policy_version")
        if not isinstance(self.version, str) or not re.match(r"^\d+\.\d+\.\d+$", self.version):
            raise InfraError("policy: policy_version must be MAJOR.MINOR.PATCH")
        lim = data.get("limits")
        if not isinstance(lim, dict):
            raise InfraError("policy: limits missing")
        missing = [k for k in REQUIRED_LIMITS if k not in lim]
        if missing:
            raise InfraError("policy: missing limits: %s" % ", ".join(missing))
        tol = lim["tolerance_cm"]
        if not isinstance(tol, dict) or any(
                not isinstance(tol.get(k), (int, float)) or tol.get(k) <= 0
                for k in ("precise", "body_adjacent", "loose")):
            raise InfraError("policy: tolerance_cm needs positive precise, body_adjacent, loose")
        self.L = lim
        self.waivable = data.get("waivable", {})
        if not isinstance(self.waivable, dict) or any(not isinstance(v, bool) for v in self.waivable.values()):
            raise InfraError("policy: waivable must map rule ids to booleans")
        self.severity_overrides = data.get("severity_overrides", {})
        if not isinstance(self.severity_overrides, dict):
            raise InfraError("policy: severity_overrides must be an object")
        for rid, sev in self.severity_overrides.items():
            if rid not in RULES or sev not in SEVERITIES:
                raise InfraError("policy: bad severity override %r: %r" % (rid, sev))
        self.legacy_severity = data.get("legacy_severity", {})
        if not isinstance(self.legacy_severity, dict):
            raise InfraError("policy: legacy_severity must be an object")
        for rid, sev in self.legacy_severity.items():
            if rid not in ("XR001", "PV001") or sev not in SEVERITIES:
                raise InfraError("policy: bad legacy_severity entry %r: %r" % (rid, sev))


class Finding(object):
    def __init__(self, rule, pointer, message, key, severity):
        self.rule = rule
        self.pointer = pointer
        self.message = message
        self.key = key
        self.severity = severity
        self.fp = hashlib.sha256(("%s|%s|%s" % (rule, pointer, key)).encode("utf-8")).hexdigest()[:16]
        self.waiver = None


class Out(object):
    def __init__(self, policy):
        self.policy = policy
        self.items = []

    def add(self, rule, pointer, message, key="", severity=None):
        if rule not in RULES:
            raise InfraError("internal: unknown rule %s" % rule)
        sev = self.policy.severity_overrides.get(rule) or severity or RULES[rule][1]
        self.items.append(Finding(rule, pointer, message, key, sev))


# ---------------------------------------------------------------- base pack accessors

def base_state_items(pack):
    """List of (pointer_token, state_dict) in pack order, or None if the structure is not recognized."""
    st = pack.get("states")
    if isinstance(st, list) and st:
        for s in st:
            if not (isinstance(s, dict) and isinstance(s.get("id"), str)):
                return None
        return [(i, s) for i, s in enumerate(st)]
    if isinstance(st, dict) and st:
        return [(k, dict(v, id=k) if isinstance(v, dict) else {"id": k}) for k, v in st.items()]
    return None


def base_state_ids(pack):
    items = base_state_items(pack)
    return None if items is None else [s["id"] for _, s in items]


def _asset_key(x):
    """The repository pack uses asset_id; id is accepted as a fallback."""
    for k in ("asset_id", "id"):
        if isinstance(x.get(k), str):
            return x[k]
    return None


def base_assets(pack):
    a = pack.get("assets")
    if isinstance(a, list):
        out = {}
        for x in a:
            key = _asset_key(x) if isinstance(x, dict) else None
            if key is None:
                return None
            out[key] = x
        return out
    if isinstance(a, dict):
        return dict((k, v) for k, v in a.items() if isinstance(v, dict))
    return None


def base_surfaces(pack):
    """target_surfaces as in the repository pack; surfaces is accepted as a fallback."""
    for key in ("target_surfaces", "surfaces"):
        s = pack.get(key)
        if isinstance(s, list):
            return [x for x in s if isinstance(x, str)]
        if isinstance(s, dict):
            return list(s.keys())
    return None


class Ctx(object):
    def __init__(self, pack, policy, now_date, state_ids, assets):
        self.pack = pack
        self.xr = pack.get("xr_layer")
        self.prov = pack.get("provenance")
        self.pol = policy
        self.L = policy.L
        self.now_end = dt.datetime(now_date.year, now_date.month, now_date.day, 23, 59, 59, tzinfo=dt.timezone.utc)
        self.state_ids = state_ids
        self.assets = assets
        self.state_items = base_state_items(pack)
        self.states = dict((s["id"], s) for _, s in self.state_items)


# ---------------------------------------------------------------- XR rules

T1_KINDS = frozenset(["image", "video_alpha"])
BILLBOARD_KINDS = frozenset(["video_alpha", "image", "image_sequence"])
# kind of the base asset manifest that may back each xr_layer.media kind
BASE_KINDS_FOR_MEDIA = {
    "video_alpha": ("xr_clip",),
    "image_sequence": ("xr_clip",),
    "image": ("image",),
    "glb": ("glb_bundle",),
}


def r_state_coverage(c, out):
    base = set(c.state_ids)
    got = set(c.xr["states"].keys())
    for sid in sorted(base - got):
        out.add("XR003", "/xr_layer/states", "state '%s' has no xr_layer entry" % sid, "missing:" + sid)
    for sid in sorted(got - base):
        out.add("XR003", P("xr_layer", "states", sid), "xr_layer describes unknown state '%s'" % sid, "unknown:" + sid)


def _asset_ref(c, out, pointer, asset_id, kinds, role):
    if asset_id not in c.assets:
        out.add("XR005", pointer, "%s '%s' is not in the pack asset manifest" % (role, asset_id), "noasset:" + asset_id)
        return
    m = c.xr["media"].get(asset_id)
    if m is None:
        out.add("XR005", pointer, "%s '%s' has no xr_layer.media descriptor" % (role, asset_id), "nomedia:" + asset_id)
        return
    if m["kind"] not in kinds:
        out.add("XR005", pointer, "%s '%s' has kind '%s', allowed: %s" % (
            role, asset_id, m["kind"], ", ".join(sorted(kinds))), "kind:" + asset_id)


def r_asset_refs(c, out):
    for mid in sorted(c.xr["media"]):
        if mid not in c.assets:
            out.add("XR005", P("xr_layer", "media", mid),
                    "media descriptor '%s' has no asset in the manifest" % mid, "orphan:" + mid)
        else:
            want = BASE_KINDS_FOR_MEDIA[c.xr["media"][mid]["kind"]]
            have = c.assets[mid].get("kind")
            if have is not None and have not in want:
                out.add("XR005", P("xr_layer", "media", mid),
                        "asset '%s' has manifest kind '%s', but media kind '%s' needs %s"
                        % (mid, have, c.xr["media"][mid]["kind"], " or ".join(want)), "basekind:" + mid)
    for sid, st in sorted(c.xr["states"].items()):
        tiers = st["tiers"]
        if "T1" in tiers:
            _asset_ref(c, out, P("xr_layer", "states", sid, "tiers", "T1", "asset"),
                       tiers["T1"]["asset"], T1_KINDS, "T1 asset")
        if "T2" in tiers:
            t2 = tiers["T2"]
            kinds = BILLBOARD_KINDS if t2["render"] == "billboard" else frozenset(["glb"])
            _asset_ref(c, out, P("xr_layer", "states", sid, "tiers", "T2", "asset"),
                       t2["asset"], kinds, "T2 asset")
            for va in t2.get("viseme_assets", []):
                _asset_ref(c, out, P("xr_layer", "states", sid, "tiers", "T2", "viseme_assets"),
                           va, frozenset(["image"]), "viseme asset")


def r_safe_state(c, out):
    ss = c.xr["safe_state"]
    if ss not in c.state_ids:
        out.add("XR006", "/xr_layer/safe_state", "safe_state '%s' is not a pack state" % ss, "unknown")
        return
    st = c.xr["states"].get(ss)
    if st is None:
        return  # XR003 reports the missing entry
    if st["motion"] != "any":
        out.add("XR006", P("xr_layer", "states", ss, "motion"),
                "safe_state must stay valid while the robot moves (motion: any)", "motion")
    for t in ("T1", "T2"):
        if t in st["tiers"]:
            out.add("XR006", P("xr_layer", "states", ss, "tiers", t),
                    "safe_state must be T0 only (static, no animation)", "tier:" + t)


def r_precise(c, out):
    modes = set(c.xr["registration"]["accepted_modes"])
    for sid, st in sorted(c.xr["states"].items()):
        t2 = st["tiers"].get("T2")
        if not t2 or t2["tolerance_class"] != "precise":
            continue
        base = P("xr_layer", "states", sid)
        if not (modes & {"marker", "hybrid"}):
            out.add("XR007", base + "/tiers/T2/tolerance_class",
                    "precise tolerance needs marker or hybrid registration in accepted_modes", "mode:" + sid)
        if st["motion"] != "stationary":
            out.add("XR007", base + "/motion",
                    "precise tolerance is only credible while the robot is stationary", "motion:" + sid)


def registration_error_cm(c, t2):
    """Upper-bound registration error for the declared envelope (spec 10.4)."""
    reg = c.xr["registration"]
    l_eff = reg["latency_budget_ms"]["pose_to_photon"] / 1000.0
    if reg["prediction"] == "constant_velocity":
        l_eff *= c.L["prediction_residual_factor"]
    off = t2["attach"]["offset_m"]
    lever = max(math.hypot(off[0], off[1]), c.L["min_lever_arm_m"])
    e_lin = reg["max_speed_mps"] * l_eff * 100.0
    e_ang = math.radians(reg["max_turn_rate_dps"]) * lever * l_eff * 100.0
    return math.hypot(e_lin, e_ang)


def r_budget(c, out):
    for sid, st in sorted(c.xr["states"].items()):
        t2 = st["tiers"].get("T2")
        if not t2 or st["motion"] != "any":
            continue
        tol = c.L["tolerance_cm"][t2["tolerance_class"]]
        e = registration_error_cm(c, t2)
        ptr = P("xr_layer", "states", sid, "tiers", "T2", "tolerance_class")
        if e > tol:
            out.add("XR008", ptr, "estimated registration error %.1f cm exceeds the %s tolerance of %s cm at the declared "
                    "speed, turn rate and latency; use a looser class or make the state stationary"
                    % (e, t2["tolerance_class"], tol), "over:" + sid)
        elif e > tol * c.L["headroom_warn_ratio"]:
            out.add("XR008", ptr, "estimated registration error %.1f cm leaves little headroom under the %s tolerance of %s cm"
                    % (e, t2["tolerance_class"], tol), "tight:" + sid, severity="warning")


def r_moving_fallback(c, out):
    states = c.xr["states"]
    for sid, st in sorted(states.items()):
        if st["motion"] != "stationary":
            continue
        ptr = P("xr_layer", "states", sid, "moving_fallback")
        fb = st.get("moving_fallback")
        if fb is None:
            out.add("XR009", P("xr_layer", "states", sid), "stationary state needs moving_fallback", "missing:" + sid)
        elif fb == sid:
            out.add("XR009", ptr, "moving_fallback must not point to the state itself", "self:" + sid)
        elif fb not in states:
            out.add("XR009", ptr, "moving_fallback '%s' is not a described state" % fb, "unknown:" + sid)
        elif states[fb]["motion"] != "any":
            out.add("XR009", ptr, "moving_fallback '%s' must itself be valid while moving (motion: any)" % fb, "notany:" + sid)


