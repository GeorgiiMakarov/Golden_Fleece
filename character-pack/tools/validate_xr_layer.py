"""validate_xr_layer.py

Gate for the XR layer (addendum A1) and the provenance block of a Character Pack.
Standard library only, Python 3.8+.

What it does
  1. Validates the xr_layer and provenance blocks against schemas/xr-layer.addendum.schema.json
     with a small built-in JSON Schema engine (the schema file stays the single source of
     truth for structure).
  2. Runs semantic rules XRnnn (XR layer over a moving robot) and PVnnn (provenance of
     avatars generated by distributors). Limits come from policy/xr-gate-policy.v1.json.
  3. Applies waivers (reason, approver, expiry, creator cannot approve their own waiver).
  4. Writes a text report and, optionally, SARIF 2.1.0 with partial fingerprints and digests
     of the tool, schema, policy and input, so that a verdict can be reproduced.

Exit codes (same convention as the ScriptCheckup CLI)
  0  clean: no findings (waived findings do not count)
  1  warnings only: pass with a mark
  2  at least one unwaived error: block
  3  infrastructure failure (unreadable input, broken schema or policy, internal error):
     block. The gate is fail-closed: a crash is never reported as a pass.

The base pack structure is read by a few tolerant accessors below (base_state_items,
base_assets, base_surfaces): target_surfaces and assets[].asset_id as in the repository
pack, with fallbacks to surfaces and assets[].id. If your base schema names things
differently, change those accessors and nothing else.

Transition for packs written before A1. A pack with neither xr_layer nor provenance is a
legacy v1 pack. XR001 and PV001 are reported for it with the severity given by
policy.legacy_severity (warning by default), so existing packs pass with a mark. As soon as
a pack carries any A1 block, both rules are errors.
"""
