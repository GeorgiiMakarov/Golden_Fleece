def _extent_box(attach, bounds):
    off, mn, mx = attach["offset_m"], bounds["min"], bounds["max"]
    r = math.hypot(max(abs(mn[0]), abs(mx[0])), max(abs(mn[1]), abs(mx[1])))
    return ((off[0] - r, off[1] - r, off[2] + mn[2]), (off[0] + r, off[1] + r, off[2] + mx[2]))


def _overlap(a, b):
    return all(a[0][i] <= b[1][i] and b[0][i] <= a[1][i] for i in range(3))


def r_keep_out(c, out):
    vols = []
    for i, v in enumerate(c.xr["keep_out"]):
        if any(v["min"][k] >= v["max"][k] for k in range(3)):
            out.add("XR012", P("xr_layer", "keep_out", i), "keep_out volume '%s' has min >= max" % v["id"], "badvol:" + v["id"])
        else:
            vols.append(v)
    for sid, st in sorted(c.xr["states"].items()):
        t2 = st["tiers"].get("T2")
        if not t2:
            continue
        b = t2["bounds_m"]
        if any(b["min"][k] >= b["max"][k] for k in range(3)):
            out.add("XR012", P("xr_layer", "states", sid, "tiers", "T2", "bounds_m"), "bounds_m has min >= max", "badbounds:" + sid)
            continue
        box = _extent_box(t2["attach"], b)
        for v in vols:
            if v["frame"] == t2["attach"]["frame"] and _overlap(box, (tuple(v["min"]), tuple(v["max"]))):
                out.add("XR012", P("xr_layer", "states", sid, "tiers", "T2", "bounds_m"),
                        "character bounds overlap keep_out volume '%s' (frame %s)" % (v["id"], v["frame"]), "keepout:%s:%s" % (sid, v["id"]))


