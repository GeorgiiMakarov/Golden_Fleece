def r_pv_coverage(c, out):
    prov = c.prov
    jobs = prov["generation"]["jobs"]
    hand = set(prov.get("hand_made_assets", []))
    owner = {}
    for i, job in enumerate(jobs):
        for aid in job["produces_assets"]:
            owner.setdefault(aid, []).append(job["job_id"])
            if aid not in c.assets:
                out.add("PV002", P("provenance", "generation", "jobs", i, "produces_assets"),
                        "job '%s' lists asset '%s' that is not in the manifest" % (job["job_id"], aid), "ghost:" + aid)
    for aid, js in sorted(owner.items()):
        if len(js) > 1:
            out.add("PV002", "/provenance/generation/jobs", "asset '%s' is claimed by several jobs: %s" % (aid, ", ".join(js)), "multi:" + aid)
        if aid in hand:
            out.add("PV002", "/provenance/hand_made_assets", "asset '%s' is both generated and hand made" % aid, "both:" + aid)
    for i, pp in enumerate(prov.get("post_processing", [])):
        for aid in pp["asset_ids"]:
            if aid not in c.assets:
                out.add("PV002", P("provenance", "post_processing", i, "asset_ids"),
                        "post-processing step '%s' references unknown asset '%s'" % (pp["step"], aid), "ppghost:" + aid)
    if c.xr is not None:
        for mid in sorted(c.xr["media"]):
            if mid not in owner and mid not in hand:
                out.add("PV002", P("xr_layer", "media", mid),
                        "XR asset '%s' is covered by neither a generation job nor hand_made_assets" % mid, "uncovered:" + mid)


def r_pv_terms(c, out):
    prov = c.prov
    te = prov["terms_evidence"]
    base = "/provenance/terms_evidence"
    if te["commercial_use"] is not True:
        out.add("PV003", base + "/commercial_use", "terms evidence does not confirm commercial use of outputs", "commercial")
    if te["watermark_free"] is not True:
        out.add("PV003", base + "/watermark_free", "terms evidence: outputs were not watermark-free", "watermark")
    if te["plan_kind"] == "free":
        out.add("PV003", base + "/plan_kind", "free plan: outputs carry a watermark and weaker rights", "free")
    cap = parse_ts(te["captured_at"])
    window = dt.timedelta(days=c.L["terms_evidence_window_days"])
    for i, job in enumerate(prov["generation"]["jobs"]):
        gen = parse_ts(job["generated_at"])
        if abs(cap - gen) > window:
            out.add("PV003", P("provenance", "generation", "jobs", i, "generated_at"),
                    "terms were captured %d days away from generation of job '%s'; capture the terms at generation time"
                    % (abs((cap - gen).days), job["job_id"]), "window:" + job["job_id"], severity="warning")
    if te["training_exposure"] == "default_may_train":
        out.add("PV008", base + "/training_exposure",
                "on this plan prompts and reference images may be used to improve the platform models; "
                "confidential characters need an enterprise agreement", "train")


