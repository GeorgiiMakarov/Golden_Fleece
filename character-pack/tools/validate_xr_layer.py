def apply_waivers(out, waivers, pack, pol, now_date):
    prov = pack.get("provenance") if isinstance(pack.get("provenance"), dict) else {}
    creator = prov.get("creator") if isinstance(prov.get("creator"), dict) else {}
    creator_org = creator.get("org_id")
    pack_version = pack.get("pack_version")
    snapshot = list(out.items)
    need = ("rule", "fingerprint", "pack_version", "reason", "approver", "approver_org", "expires")
    for i, w in enumerate(waivers):
        loc = "waivers#/%d" % i
        if not isinstance(w, dict):
            out.add("WV001", loc, "waiver %d is not an object" % i, "w%d:shape" % i)
            continue
        miss = [k for k in need if not isinstance(w.get(k), str) or not w.get(k).strip()]
        exp = parse_date(w.get("expires")) if isinstance(w.get("expires"), str) else None
        if miss or exp is None:
            out.add("WV001", loc, "waiver %d malformed (missing/blank: %s%s)" % (
                i, ", ".join(miss) or "none", "; expires must be YYYY-MM-DD" if exp is None else ""), "w%d:malformed" % i)
            continue
        targets = [f for f in snapshot if f.rule == w["rule"] and f.fp == w["fingerprint"]]
        if not targets:
            out.add("WV001", loc, "waiver %d for %s matches no current finding (stale waiver?)" % (i, w["rule"]), "w%d:nomatch" % i)
            continue
        why = []
        if w["pack_version"] != pack_version:
            why.append("pack_version %s != %s" % (w["pack_version"], pack_version))
        if exp < now_date:
            why.append("expired on %s" % w["expires"])
        elif (exp - now_date).days > pol.L["max_waiver_days"]:
            why.append("expires more than %d days ahead" % pol.L["max_waiver_days"])
        if len(w["reason"].strip()) < pol.L["min_waiver_reason_chars"]:
            why.append("reason shorter than %d characters" % pol.L["min_waiver_reason_chars"])
        if creator_org and w["approver_org"].strip() == creator_org:
            why.append("approver belongs to the creator organisation")
        if not pol.waivable.get(w["rule"], False):
            why.append("rule %s is not waivable" % w["rule"])
        if why:
            out.add("WV001", loc, "waiver %d for %s rejected: %s" % (i, w["rule"], "; ".join(why)), "w%d:rejected" % i)
        else:
            for f in targets:
                f.waiver = w


def exit_code(items):
    live = [f for f in items if f.waiver is None]
    if any(f.severity == "error" for f in live):
        return EXIT_ERROR
    if any(f.severity == "warning" for f in live):
        return EXIT_WARN
    return EXIT_CLEAN


class Report(object):
    def __init__(self):
        self.findings = []
        self.code = EXIT_INFRA
        self.pack_uri = ""
        self.digests = {}
        self.policy = None
        self.notes = []


def _rel(path):
    try:
        return os.path.relpath(str(path)).replace(os.sep, "/")
    except ValueError:
        return Path(path).name


def evaluate(pack_path, schema_path=DEFAULT_SCHEMA, policy_path=DEFAULT_POLICY, waivers_path=None, now_date=None):
    rep = Report()
    rep.pack_uri = _rel(pack_path)
    rep.digests["validator_sha256"] = sha256_bytes(Path(__file__).read_bytes())
    now_date = now_date or dt.date.today()
    schema, rep.digests["schema_sha256"] = load_json(schema_path, "schema")
    audit_schema(schema)
    pol_data, rep.digests["policy_sha256"] = load_json(policy_path, "policy")
    pol = Policy(pol_data)
    rep.policy = pol
    rep.digests["policy_version"] = pol.version
    pack, rep.digests["input_sha256"] = load_json(pack_path, "pack")
    if not isinstance(pack, dict):
        raise InfraError("pack root must be a JSON object")
    waivers = _load_waivers(waivers_path) if waivers_path else []
    out = Out(pol)
    run_rules(pack, schema, pol, now_date, out)
    if waivers:
        apply_waivers(out, waivers, pack, pol, now_date)
    rep.findings = sorted(out.items, key=lambda f: (f.rule, f.pointer, f.fp))
    rep.code = exit_code(rep.findings)
    return rep


