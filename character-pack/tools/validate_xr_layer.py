def r_media(c, out):
    for mid, m in sorted(c.xr["media"].items()):
        ptr = P("xr_layer", "media", mid)
        if m["watermark_free"] is not True:
            out.add("XR020", ptr + "/watermark_free", "media '%s' carries a platform watermark" % mid, "watermark:" + mid)
        kind = m["kind"]
        if kind in ("video_alpha", "image_sequence"):
            for need in ("width", "height", "fps", "duration_ms"):
                if need not in m:
                    out.add("XR020", ptr, "%s '%s' needs '%s'" % (kind, mid, need), "need:%s:%s" % (need, mid))
            if "fps" in m and m["fps"] not in c.L["allowed_fps"]:
                out.add("XR020", ptr + "/fps", "fps %s is not in %s" % (m["fps"], c.L["allowed_fps"]), "fps:" + mid)
            if "duration_ms" in m and m["duration_ms"] > c.L["max_clip_ms"]:
                out.add("XR020", ptr + "/duration_ms", "duration %d ms exceeds %d" % (m["duration_ms"], c.L["max_clip_ms"]), "dur:" + mid)
            if "width" in m and "height" in m and m["width"] * m["height"] > c.L["max_frame_pixels"]:
                out.add("XR020", ptr, "frame %dx%d exceeds %d pixels" % (m["width"], m["height"], c.L["max_frame_pixels"]), "pixels:" + mid)
        if kind == "video_alpha":
            if m.get("has_audio") is not False:
                out.add("XR020", ptr + "/has_audio", "video_alpha '%s' must declare has_audio: false (audio comes from the robot TTS)" % mid, "audio:" + mid)
            am = m.get("alpha_mode")
            if am not in ("packed_lr", "packed_tb", "native_vp9"):
                out.add("XR020", ptr + "/alpha_mode", "video_alpha '%s' needs alpha_mode packed_lr, packed_tb or native_vp9" % mid, "alpha:" + mid)
            elif am == "packed_lr" and "width" in m and m["width"] % 2:
                out.add("XR020", ptr + "/width", "packed_lr needs an even encoded width", "evenw:" + mid)
            elif am == "packed_tb" and "height" in m and m["height"] % 2:
                out.add("XR020", ptr + "/height", "packed_tb needs an even encoded height", "evenh:" + mid)
            lp = m.get("loop")
            if lp is not None and "duration_ms" in m:
                if not (0 <= lp["in_ms"] < lp["out_ms"] <= m["duration_ms"]):
                    out.add("XR020", ptr + "/loop", "loop needs 0 <= in_ms < out_ms <= duration_ms", "loop:" + mid)
                elif lp["out_ms"] - lp["in_ms"] < c.L["min_loop_ms"]:
                    out.add("XR020", ptr + "/loop", "loop shorter than %d ms repeats visibly" % c.L["min_loop_ms"], "looplen:" + mid)
        if kind in ("image", "video_alpha", "image_sequence") and ("width" not in m or "height" not in m):
            out.add("XR020", ptr, "%s '%s' needs width and height" % (kind, mid), "size:" + mid)
        if kind == "glb":
            if "triangles" not in m or "texture_max_px" not in m:
                out.add("XR020", ptr, "glb '%s' needs triangles and texture_max_px" % mid, "glbneed:" + mid)
            else:
                if m["triangles"] > c.L["max_glb_triangles"]:
                    out.add("XR020", ptr + "/triangles", "%d triangles exceed %d" % (m["triangles"], c.L["max_glb_triangles"]), "tris:" + mid)
                if m["texture_max_px"] > c.L["max_texture_px"]:
                    out.add("XR020", ptr + "/texture_max_px", "texture %d px exceeds %d" % (m["texture_max_px"], c.L["max_texture_px"]), "tex:" + mid)


def r_budget_bytes(c, out):
    total = 0
    for mid in sorted(c.xr["media"]):
        a = c.assets.get(mid)
        if a is None:
            continue
        b = a.get("bytes")
        if not isinstance(b, int) or isinstance(b, bool):
            out.add("XR021", P("xr_layer", "media", mid), "asset '%s' has no integer bytes: the budget cannot be verified" % mid,
                    "nobytes:" + mid, severity="warning")
            continue
        if b == 0:
            out.add("XR021", P("xr_layer", "media", mid), "asset '%s' declares bytes: 0 (placeholder?)" % mid,
                    "zero:" + mid, severity="warning")
        total += b
    if total > c.L["max_xr_media_bytes"]:
        out.add("XR021", "/xr_layer/media", "XR media totals %d bytes, limit %d" % (total, c.L["max_xr_media_bytes"]), "total")


def r_visemes(c, out):
    for sid, st in sorted(c.xr["states"].items()):
        t2 = st["tiers"].get("T2")
        if not t2:
            continue
        va = t2.get("viseme_assets", [])
        ptr = P("xr_layer", "states", sid, "tiers", "T2", "speaking_driver")
        if t2["speaking_driver"] == "viseme_lite" and not (3 <= len(va) <= 5):
            out.add("XR022", ptr, "viseme_lite needs 3 to 5 viseme_assets, found %d" % len(va), "count:" + sid)
        if t2["speaking_driver"] != "viseme_lite" and va:
            out.add("XR022", ptr, "viseme_assets given but speaking_driver is '%s'" % t2["speaking_driver"], "extra:" + sid)


def r_device_tiers(c, out):
    dc = set(c.xr["device_classes"])
    can_t1 = bool(dc & {"display_ai_glasses", "wired_xr_glasses", "xr_headset"})
    can_t2 = bool(dc & {"wired_xr_glasses", "xr_headset"})
    for sid, st in sorted(c.xr["states"].items()):
        t = st["tiers"]
        if "T1" in t and not can_t1:
            out.add("XR024", P("xr_layer", "states", sid, "tiers", "T1"), "T1 declared, but no listed device class has a display", "t1:" + sid)
        if "T2" in t and not can_t2:
            out.add("XR024", P("xr_layer", "states", sid, "tiers", "T2"),
                    "T2 declared, but only display_ai_glasses (T2 only if the host confirms world anchoring) or audio classes are listed",
                    "t2:" + sid)


def r_voice_alignment(c, out):
    """line_id is '<state_id>#<index>', so the voice_lines arrays of one state must be index-aligned."""
    for token, st in c.state_items:
        vl = st.get("voice_lines")
        if not isinstance(vl, dict) or not vl:
            continue
        lengths = dict((loc, len(v)) for loc, v in vl.items() if isinstance(v, list))
        if len(set(lengths.values())) > 1:
            out.add("XR025", P("states", token, "voice_lines"),
                    "state '%s': voice_lines lengths differ across locales (%s); line_id '%s#<index>' needs "
                    "index-aligned arrays" % (st["id"], ", ".join("%s=%d" % kv for kv in sorted(lengths.items())), st["id"]),
                    "len:" + st["id"])


def r_glb_consistency(c, out):
    for sid, st in sorted(c.xr["states"].items()):
        t2 = st["tiers"].get("T2")
        if not t2 or t2["render"] != "glb":
            continue
        xr1 = c.states.get(sid, {}).get("xr")
        bundle = xr1.get("bundle_asset") if isinstance(xr1, dict) else None
        if bundle is not None and bundle != t2["asset"]:
            out.add("XR026", P("xr_layer", "states", sid, "tiers", "T2", "asset"),
                    "T2 glb asset '%s' differs from xr.bundle_asset '%s' of the v1 state" % (t2["asset"], bundle),
                    "glb:" + sid)


