def render_text(rep):
    lines = ["%s %s, policy %s" % (TOOL_NAME, TOOL_VERSION, rep.digests.get("policy_version", "?")),
             "pack: %s (sha256 %s)" % (rep.pack_uri, rep.digests.get("input_sha256", "?")[:16])]
    errors = warnings = waived = 0
    for f in rep.findings:
        if f.waiver is not None:
            tag, waived = "WAIVED ", waived + 1
        elif f.severity == "error":
            tag, errors = "ERROR  ", errors + 1
        elif f.severity == "warning":
            tag, warnings = "WARN   ", warnings + 1
        else:
            tag = "NOTE   "
        lines.append("%s %s %s  %s  [fp=%s]" % (tag, f.rule, f.pointer, f.message, f.fp))
    lines.append("Summary: %d error(s), %d warning(s), %d waived" % (errors, warnings, waived))
    lines.append("exit %d" % rep.code)
    return "\n".join(lines)


def _lvl(sev):
    return {"error": "error", "warning": "warning"}.get(sev, "note")


def to_sarif(rep, infra_message=None):
    pol = rep.policy
    rules = []
    for rid in sorted(RULES):
        title, sev = RULES[rid]
        rules.append({
            "id": rid, "name": rid, "shortDescription": {"text": title},
            "defaultConfiguration": {"level": _lvl(sev)},
            "properties": {"waivable": bool(pol.waivable.get(rid, False)) if pol else False},
        })
    results = []
    for f in rep.findings:
        r = {
            "ruleId": f.rule, "level": _lvl(f.severity), "message": {"text": f.message},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": rep.pack_uri}},
                           "logicalLocations": [{"fullyQualifiedName": f.pointer, "kind": "member"}]}],
            "partialFingerprints": {"charpack/v1": f.fp},
        }
        if f.waiver is not None:
            r["suppressions"] = [{
                "kind": "external", "status": "accepted", "justification": f.waiver["reason"],
                "properties": {"approver": f.waiver["approver"], "approver_org": f.waiver["approver_org"],
                               "expires": f.waiver["expires"]},
            }]
        results.append(r)
    notifications = []
    if infra_message:
        notifications.append({"level": "error", "message": {"text": infra_message}})
    props = dict(rep.digests)
    props["tool_version"] = TOOL_VERSION
    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": TOOL_NAME, "version": TOOL_VERSION, "rules": rules}},
            "artifacts": [{"location": {"uri": rep.pack_uri},
                           "hashes": ({"sha-256": rep.digests["input_sha256"]} if "input_sha256" in rep.digests else {})}],
            "results": results,
            "invocations": [{"executionSuccessful": rep.code != EXIT_INFRA, "exitCode": rep.code,
                             "toolExecutionNotifications": notifications}],
            "properties": props,
        }],
    }


def write_sarif(path, sarif):
    try:
        Path(path).write_text(json.dumps(sarif, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    except OSError as e:
        raise InfraError("cannot write SARIF %s: %s" % (path, e))


def list_rules(policy_path):
    pol = None
    try:
        pol = Policy(load_json(policy_path, "policy")[0])
    except InfraError:
        pass
    print("%-6s %-8s %-10s %s" % ("rule", "severity", "waivable", "title"))
    for rid in sorted(RULES):
        title, sev = RULES[rid]
        w = "?" if pol is None else ("yes" if pol.waivable.get(rid, False) else "no")
        print("%-6s %-8s %-10s %s" % (rid, sev, w, title))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Gate for the XR layer (addendum A1) and provenance of a Character Pack.")
    ap.add_argument("pack", nargs="?", help="path to the pack JSON")
    ap.add_argument("--schema", default=str(DEFAULT_SCHEMA))
    ap.add_argument("--policy", default=str(DEFAULT_POLICY))
    ap.add_argument("--waivers", help="JSON file with waivers")
    ap.add_argument("--sarif", help="write SARIF 2.1.0 to this path")
    ap.add_argument("--now", help="evaluation date YYYY-MM-DD (default: today); used for waiver expiry and future timestamps")
    ap.add_argument("--list-rules", action="store_true")
    args = ap.parse_args(argv)

    if args.list_rules:
        list_rules(args.policy)
        return EXIT_CLEAN
    if not args.pack:
        ap.error("pack is required")

    rep = Report()
    rep.pack_uri = _rel(args.pack)
    try:
        now = parse_date(args.now) if args.now else None
        if args.now and now is None:
            raise InfraError("--now must be YYYY-MM-DD")
        rep = evaluate(args.pack, args.schema, args.policy, args.waivers, now)
        if args.sarif:
            write_sarif(args.sarif, to_sarif(rep))
        print(render_text(rep))
        return rep.code
    except InfraError as e:
        msg = "INFRASTRUCTURE FAILURE: %s" % e
    except Exception as e:  # a bug is an infrastructure failure, never a pass
        msg = "INFRASTRUCTURE FAILURE: unexpected %s: %s" % (type(e).__name__, e)
    print(msg, file=sys.stderr)
    rep.code = EXIT_INFRA
    if args.sarif:
        try:
            write_sarif(args.sarif, to_sarif(rep, infra_message=msg))
        except InfraError as e2:
            print(str(e2), file=sys.stderr)
    return EXIT_INFRA


if __name__ == "__main__":
    sys.exit(main())
